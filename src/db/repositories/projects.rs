/// Checks whether a project with the given id exists.
pub async fn exists<'e>(exec: impl PgExecutor<'e>, id: Uuid) -> Result<bool, DbError> {
    let exists = sqlx::query_scalar!("SELECT EXISTS(SELECT 1 FROM projects WHERE id = $1)", id)
        .fetch_one(exec)
        .await?;
    Ok(exists.unwrap_or(false))
}

/// Inserts a new project row. `id` is generated by the caller (rather than relying on the
/// column default + `RETURNING`) so callers can prepare on-disk state (e.g. an uploads
/// directory) under the same id before/without a round trip.
#[allow(clippy::too_many_arguments)]
pub async fn insert(
    pool: &PgPool,
    id: Uuid,
    title: &str,
    description: Option<&str>,
    template_id: Option<Uuid>,
    folder: Option<Uuid>,
    owner_team_id: Uuid,
) -> Result<(), DbError> {
    sqlx::query!(
        "INSERT INTO projects (id, title, description, template_id, folder, owner_team_id)
         VALUES ($1, $2, $3, $4, $5, $6)",
        id,
        title,
        description,
        template_id,
        folder,
        owner_team_id
    )
    .execute(pool)
    .await?;
    Ok(())
}

/// Fetches a project's title.
pub async fn get_title<'e>(exec: impl PgExecutor<'e>, id: Uuid) -> Result<String, DbError> {
    sqlx::query_scalar!("SELECT title FROM projects WHERE id = $1", id)
        .fetch_optional(exec)
        .await?
        .ok_or(DbError::NotFound("project"))
}

/// Updates a project's title. Fails with [`DbError::NotFound`] if no project with that id exists.
pub async fn update_title<'e>(
    exec: impl PgExecutor<'e>,
    id: Uuid,
    title: &str,
) -> Result<(), DbError> {
    let result = sqlx::query!("UPDATE projects SET title = $2 WHERE id = $1", id, title)
        .execute(exec)
        .await?;
    if result.rows_affected() == 0 {
        return Err(DbError::NotFound("project"));
    }
    Ok(())
}

