//! `projects` / `persons_projects`.
//!
//! `ProjectMetadataV5` and `ProjectSettingsV5` both implement `sqlx::FromRow` (the former
//! directly on the local type in `storage::project_storage::current`, the latter on the
//! `vb-exchange` type itself, behind its `sqlx` feature — see their `FromRow` impls for the
//! per-field mapping notes). `ProjectMetadataV5`'s `authors`/`editors` still need a separate
//! fetch from the `persons_projects` join afterward, since that's not a plain column.
//!
//! Known schema gaps (inherited from the existing migration/schema, not introduced here):
//! `ProjectSettingsV5.metadata_page_additional_html` has no column, always round-trips as
//! `None`. `title` is the single unified column for both the old `ProjectData.name` and
//! `ProjectMetadata.title` (which could previously diverge) — every write keeps them equal.

