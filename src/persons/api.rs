    #[sqlx::test]
    async fn projects_only_accept_persons_of_their_own_scope(pool: PgPool) -> sqlx::Result<()> {
        let w = world(pool).await;
        let (_, mine) = create(&w.alice, json!({"Team": w.team})).await;
        let (_, theirs) = create(&w.bob, json!({"Team": w.other_team})).await;
        let (_, private_to_other) = create(&w.bob, json!({"Project": w.other_project})).await;

        let patch = |author: &Value| {
            w.alice
                .patch(format!("/api/projects/{}", w.project))
                .header(ContentType::JSON)
                .body(
                    json!({"metadata": {"authors": [{"PersonUuid": author["data"]["id"]}]}})
                        .to_string(),
                )
                .dispatch()
        };
        assert_eq!(patch(&mine).await.status(), Status::Ok);
        assert_eq!(patch(&theirs).await.status(), Status::NotFound);
        assert_eq!(patch(&private_to_other).await.status(), Status::NotFound);

        // free-text names are always fine
        let response = w
            .alice
            .patch(format!("/api/projects/{}", w.project))
            .header(ContentType::JSON)
            .body(json!({"metadata": {"editors": [{"NameString": "Guest"}]}}).to_string())
            .dispatch()
            .await;
        assert_eq!(response.status(), Status::Ok);

        // and a user outside the project's team can't patch it at all
        let response = w
            .bob
            .patch(format!("/api/projects/{}", w.project))
            .header(ContentType::JSON)
            .body(json!({"name": "Hijacked"}).to_string())
            .dispatch()
            .await;
        assert_eq!(response.status(), Status::NotFound);
        Ok(())
    }
