/// POST /api/persons/
/// Create a new person. `scope` is required: `{"Team": <team id>}` adds the person to that
/// team's library, `{"Project": <project id>}` makes it private to that project. The user
/// needs access to the team/project.
#[post("/api/persons", data = "<person>")]
pub async fn create_person(
    session: Session,
    pool: &State<PgPool>,
    person: Json<Person>,
) -> APIResult<Person> {
    let mut person = person.into_inner();

    match person.scope {
        Some(PersonScope::Team(team_id)) => {
            has_permission(pool, ResourceType::Team, team_id, session.user_id, None).await?;
        }
        Some(PersonScope::Project(project_id)) => {
            has_permission(
                pool,
                ResourceType::Project,
                project_id,
                session.user_id,
                None,
            )
            .await?;
        }
        None => {
            return Err(ApiErrorType::BadRequest(
                "Person needs a scope (Team or Project)".to_string(),
            )
            .into());
        }
    }

    // Check if api request contains a person id, if so return an error as the id is generated by the server
    match person.id {
        Some(_) => {
            eprintln!("Person already has an id");
            return Err(ApiErrorType::BadRequest(
                "Person is not supposed to have an id".to_string(),
            )
            .into());
        }
        None => {
            person.id = Some(uuid::Uuid::new_v4());
        }
    }

    if let Some(ref mut gnd) = person.gnd {
        if gnd.id.is_none() {
            gnd.id = Some(uuid::Uuid::new_v4());
        } else {
            eprintln!("Persons gnd already has a id");
            return Err(
                ApiErrorType::BadRequest("GND is not supposed to have an id".to_string()).into(),
            );
        }
    };

    if let Some(ref mut orcid) = person.orcid {
        if orcid.id.is_none() {
            orcid.id = Some(uuid::Uuid::new_v4());
        } else {
            eprintln!("Persons orcid already has a id");
            return Err(ApiErrorType::BadRequest(
                "ORCID is not supposed to have an id".to_string(),
            )
            .into());
        }
    };

    if let Some(ref mut ror) = person.ror {
        if ror.id.is_none() {
            ror.id = Some(uuid::Uuid::new_v4());
        } else {
            eprintln!("Persons ror already has a id");
            return Err(
                ApiErrorType::BadRequest("ROR is not supposed to have an id".to_string()).into(),
            );
        }
    };

    persons::insert(pool.inner(), &person).await?;

    Ok(APIResponse::from(person))
}

/// PUT /api/persons/<id>
/// Update specified person. A `scope` in the body is ignored: the scope only changes through
/// `POST /api/persons/<id>/promote`.
#[put("/api/persons/<id>", data = "<person>")]
pub async fn update_person(
    session: Session,
    pool: &State<PgPool>,
    person: Json<Person>,
    id: &str,
) -> APIResult<Person> {
    let person = person.into_inner();
    let id = parse_uuid(id)?;

    has_permission(pool, ResourceType::Person, id, session.user_id, None).await?;

    // Check if id in url matches id in body
    match person.id {
        Some(ref person_id) => {
            if *person_id != id {
                eprintln!("Person id in url doesn't match person id in body");
                return Err(ApiErrorType::BadRequest(
                    "Person id in url doesn't match person id in body. ID change is not allowed"
                        .to_string(),
                )
                .into());
            }
        }
        None => {
            eprintln!("Person doesn't have an id");
            return Err(ApiErrorType::BadRequest("Person doesn't have an id".to_string()).into());
        }
    }

    persons::update(pool.inner(), &person).await?;

    // Re-read so the response shows the stored state (in particular the real scope).
    Ok(APIResponse::from(persons::get(pool.inner(), id).await?))
}

// GET /api/persons/<id>
/// Get a person by id
#[get("/api/persons/<id>")]
pub async fn get_person(session: Session, pool: &State<PgPool>, id: String) -> APIResult<Person> {
    let id = parse_uuid(&id)?;
    has_permission(pool, ResourceType::Person, id, session.user_id, None).await?;
    let person = persons::get(pool.inner(), id).await?;
    Ok(APIResponse::from(person))
}

/// GET /api/persons?query=<query>&project_id=<id> | team_id=<id>
/// Search for persons within one scope
///
/// Arguments
/// * `query` - Query string as [`String`] - search for persons with first name, last name, orcid, gnd, or ror. Case Insensitive
/// * `limit` - Limit of results as [`Option<u16>`] - optional, default is 10
/// * `project_id` - search the project's own persons plus its team's library
/// * `team_id` - search that team's library only
///
/// Exactly one of `project_id` and `team_id` is required.
///
/// Returns
/// * `Json<ApiResult<Vec<Person>>>` - Api Result with Json List of persons matching the query
#[get("/api/persons?<query>&<limit>&<project_id>&<team_id>")]
pub async fn search_persons(
    session: Session,
    pool: &State<PgPool>,
    query: String,
    limit: Option<usize>,
    project_id: Option<String>,
    team_id: Option<String>,
) -> APIResult<Vec<Person>> {
    let limit = limit.unwrap_or(10) as i64;
    let filter = match (project_id, team_id) {
        (Some(project_id), None) => {
            let project_id = parse_uuid(&project_id)?;
            has_permission(
                pool,
                ResourceType::Project,
                project_id,
                session.user_id,
                None,
            )
            .await?;
            ScopeFilter::Project(project_id)
        }
        (None, Some(team_id)) => {
            let team_id = parse_uuid(&team_id)?;
            has_permission(pool, ResourceType::Team, team_id, session.user_id, None).await?;
            ScopeFilter::Team(team_id)
        }
        _ => {
            return Err(ApiErrorType::BadRequest(
                "Exactly one of project_id and team_id is required".to_string(),
            )
            .into());
        }
    };
    let result = persons::search(pool.inner(), &query, limit, filter).await?;
    Ok(APIResponse::from(result))
}

